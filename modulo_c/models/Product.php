<?php

namespace app\models;

use Yii;
use yii\web\ForbiddenHttpException;

/**
 * This is the model class for table "Product".
 *
 * @property string $productId
 * @property string $categoryId
 * @property string $name
 * @property string|null $description
 * @property float $price
 * @property string $code
 * @property string|null $photo
 *
 * @property Category $category
 * @property Coupon[] $coupons
 * @property Market[] $markets
 * @property SupplyData[] $supplyDatas
 */
class Product extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'Product';
    }

    /**
     * Validações do tipo de usuário
     * @param $insert
     * @return bool
     * @throws ForbiddenHttpException
     */
    public function beforeSave($insert)
    {
        $user = Yii::$app->user->identity;
        if ($user->role->title !== 'admin') {
            throw new ForbiddenHttpException('Unauthorized user');
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * validações do tipo de usuário
     * @return bool
     * @throws ForbiddenHttpException
     */
    public function beforeDelete()
    {
        $user = Yii::$app->user->identity;
        if ($user->role->title !== 'admin') {
            throw new ForbiddenHttpException('Unauthorized user');
        }
        return parent::beforeDelete(); // TODO: Change the autogenerated stub
    }

    public function fields()
    {
        return [
            'productId',
            'name',
            'description',
            'categoryId',
            'price',
            'code',
            'photo',
            'saleAmount' => fn()=> 0,
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['description', 'photo'], 'default', 'value' => null],
            [['categoryId', 'name', 'price', 'code'], 'required'],
            [['price'], 'number', 'min' => '0.01'],
            [['photo'], 'string'],
            [['productId', 'categoryId'], 'string', 'max' => 33],
            [['name'], 'string', 'max' => 100],
            [['description'], 'string', 'max' => 300],
            [['code'], 'integer'],
            [['code'], 'string', 'length' => 13],
            [['productId'], 'unique'],
            [['productId'], 'default', 'value' => Yii::$app->security->generateRandomString(33)],
            [['categoryId'], 'exist', 'skipOnError' => true, 'targetClass' => Category::class, 'targetAttribute' => ['categoryId' => 'categoryId']],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'productId' => 'Product ID',
            'categoryId' => 'Category ID',
            'name' => 'Name',
            'description' => 'Description',
            'price' => 'Price',
            'code' => 'Code',
            'photo' => 'Photo',
        ];
    }

    /**
     * Gets query for [[Category]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getCategory()
    {
        return $this->hasOne(Category::class, ['categoryId' => 'categoryId']);
    }

    /**
     * Gets query for [[Coupons]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getCoupons()
    {
        return $this->hasMany(Coupon::class, ['productId' => 'productId']);
    }

    /**
     * Gets query for [[Markets]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getMarkets()
    {
        return $this->hasMany(Market::class, ['marketId' => 'marketId'])->viaTable('SupplyData', ['productId' => 'productId']);
    }

    /**
     * Gets query for [[SupplyDatas]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getSupplyDatas()
    {
        return $this->hasMany(SupplyData::class, ['productId' => 'productId']);
    }

    public function getId()
    {
        return $this->productId;
    }

}
