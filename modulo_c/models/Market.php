<?php

namespace app\models;

use Yii;
use yii\web\ForbiddenHttpException;

/**
 * This is the model class for table "Market".
 *
 * @property string $marketId
 * @property string $address
 * @property string|null $phone
 * @property float $latitude
 * @property float $longitude
 *
 * @property Coupon[] $coupons
 * @property Employee[] $employees
 * @property Product[] $products
 * @property SupplyData[] $supplyDatas
 */
class Market extends \yii\db\ActiveRecord
{

    /**
     * Validações do tipo de usuário
     * @param $insert
     * @return bool
     * @throws ForbiddenHttpException
     */
    public function beforeSave($insert)
    {
        $user = Yii::$app->user->identity;
        if ($user->role->title !== 'admin') {
            throw new ForbiddenHttpException('You dont have necessary access');
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * validações do tipo de usuário
     * @return bool
     * @throws ForbiddenHttpException
     */
    public function beforeDelete()
    {
        $user = Yii::$app->user->identity;
        if ($user->role->title !== 'admin') {
            throw new ForbiddenHttpException('You dont have necessary access');
        }
        return parent::beforeDelete(); // TODO: Change the autogenerated stub
    }

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'Market';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['phone'], 'default', 'value' => null],
            [['address', 'latitude', 'longitude'], 'required'],
            [['latitude'], 'number', 'min' => -90, 'max' => 90],
            [['longitude'], 'number', 'min' => -180, 'max' => 180],
            [['marketId'], 'string', 'max' => 33],
            [['address'], 'string', 'max' => 500],
            [['phone'], 'string', 'length' => 11],
            [['marketId'], 'default', 'value' => Yii::$app->security->generateRandomString(33)],
            [['marketId'], 'unique'],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'marketId' => 'Market ID',
            'address' => 'Address',
            'phone' => 'Phone',
            'latitude' => 'Latitude',
            'longitude' => 'Longitude',
        ];
    }

    /**
     * Gets query for [[Coupons]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getCoupons()
    {
        return $this->hasMany(Coupon::class, ['marketId' => 'marketId']);
    }

    /**
     * Gets query for [[Employees]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getEmployees()
    {
        return $this->hasMany(Employee::class, ['marketId' => 'marketId']);
    }

    /**
     * Gets query for [[Products]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getProducts()
    {
        return $this->hasMany(Product::class, ['productId' => 'productId'])->viaTable('SupplyData', ['marketId' => 'marketId']);
    }

    /**
     * Gets query for [[SupplyDatas]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getSupplyDatas()
    {
        return $this->hasMany(SupplyData::class, ['marketId' => 'marketId']);
    }

    public function getId()
    {
        return $this->marketId;
    }

}
