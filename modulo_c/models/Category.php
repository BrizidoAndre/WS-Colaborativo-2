<?php

namespace app\models;

use Yii;
use yii\web\ForbiddenHttpException;
use yii\web\NotFoundHttpException;

/**
 * This is the model class for table "Category".
 *
 * @property string $categoryId
 * @property string $name
 * @property string|null $description
 *
 * @property Coupon[] $coupons
 * @property Product[] $products
 */
class Category extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'Category';
    }

    /**
     * Validações do tipo de usuário
     * @param $insert
     * @return bool
     * @throws ForbiddenHttpException
     */
    public function beforeSave($insert)
    {
        $user = Yii::$app->user->identity;
        if ($user->role->title !== 'admin') {
            throw new ForbiddenHttpException('Unauthorized user');
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * validações do tipo de usuário
     * @return bool
     * @throws ForbiddenHttpException
     */
    public function beforeDelete()
    {
        $user = Yii::$app->user->identity;
        if ($user->role->title !== 'admin') {
            throw new ForbiddenHttpException('Unauthorized user');
        }
        return parent::beforeDelete(); // TODO: Change the autogenerated stub
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {

        return [
            [['description'], 'default', 'value' => null],
            [['name'], 'required'],
            [['categoryId'], 'default', 'value' => Yii::$app->security->generateRandomString(33)],
            [['name'], 'string', 'max' => 100],
            [['categoryId'], 'string', 'max' => 33],
            [['name'], 'string', 'max' => 100],
            [['description'], 'string', 'max' => 300],
            [['categoryId'], 'unique'],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'categoryId' => 'Category ID',
            'name' => 'Name',
            'description' => 'Description',
        ];
    }

    /**
     * Gets query for [[Coupons]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getCoupons()
    {
        return $this->hasMany(Coupon::class, ['categoryId' => 'categoryId']);
    }

    /**
     * Gets query for [[Products]].
     *
     * @return \yii\db\ActiveQuery
     */
    public function getProducts()
    {
        return $this->hasMany(Product::class, ['categoryId' => 'categoryId']);
    }

    /**
     * @return string
     */
    public function getCategoryId(): string
    {
        return $this->categoryId;
    }

    public function getId()
    {
        return $this->categoryId;
    }

}
