<?php

namespace app\models;

use yii\web\ForbiddenHttpException;

class EmployeeUser extends User
{
    public $marketId;
    public $photo;
    public $role;

    public function rules()
    {
        return array_merge([
            [['name', 'email', 'phone', 'password', 'marketId', 'role', 'photo'], 'required'],
            ['role','in','range' => ['manager','employee']],
            ['email','unique'],
            ['phone','string','length' => 11],
            ['password', 'match', 'pattern' => '/[A-Z]{2,}/'],
            ['password', 'match', 'pattern' => '/[a-z]{2,}/'],
            ['password', 'match', 'pattern' => '/[\@\#\&\?\-\_]{2,}/i'],
            [['marketId'], 'exist', 'skipOnError' => true, 'targetClass' => Market::class, 'targetAttribute' => ['marketId' => 'marketId']],
            ['userId', 'default', 'value' => \Yii::$app->security->generateRandomString(33)],
            ['roleId', 'default', 'value' => 'iG8n1I6YXe5n6ayfu5rPmkdw0bCkVOKF'],
            [['photo'], 'string'],
        ]);
    }

    public function beforeSave($insert)
    {
        $user = \Yii::$app->user->identity;
        if ($user->role->title !== 'admin' && $user->role->title !== 'manager') {
            throw new ForbiddenHttpException('Unauthorized user');
        }
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    public function afterSave($insert, $changedAttributes)
    {
        $employee = new Employee();
        $employee->employeeId = $this->userId;
        $employee->marketId = $this->marketId;
        $employee->photo = $this->photo;
        $employee->save(false);
        parent::afterSave($insert, $changedAttributes); // TODO: Change the autogenerated stub
    }
}